using DeskWidgets.Pixel;

namespace DeskWidgets.Dock;

/// <summary>
/// The 13 custom app tiles of the Pixel dock and its generic program tile (the Pixel dock design's HANDOFF sections 1 and 2), idle and
/// awake, drawn on each size's own grid (20, 24 and 32 art px; nothing is scaled), with each app's halo colour. Copied symbol for symbol from
/// the design's <c>sprites.txt</c>: each block is the whole tile, outline and shade lip included, in <see cref="PixelPalette.Sprite"/> roles.
/// Keys are <see cref="Widgets.Folder.AppIconPack"/>'s. The generic tile has no awake drawing.
/// </summary>
internal static class PixelDockSprites
{
    /// <summary>The idle tile of a custom app at an icon size (20, 24 or 32), or null when the key or size has none.</summary>
    public static PixelSprite? Idle(string key, int size) => s_idle.TryGetValue((key, size), out var sprite) ? sprite : null;

    /// <summary>The awake tile (the running look) of a custom app, or null when it has none (the generic tile keeps its idle drawing).</summary>
    public static PixelSprite? Awake(string key, int size) => s_awake.TryGetValue((key, size), out var sprite) ? sprite : null;

    /// <summary>The sprite symbol of an app's halo (<c>halo=</c> in sprites.txt), before the readability step; null for an unknown key.</summary>
    public static char? Halo(string key) => s_halo.TryGetValue(key, out char symbol) ? symbol : null;

    /// <summary>The generic program tile (a silver tile holding a small program window): a program whose real icon has not come, or that has none.</summary>
    public static PixelSprite Generic(int size) => s_idle[("generic", size)];

